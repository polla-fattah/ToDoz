"""Builds the web client (server/web) and embeds the result in the server, so the compiled server needs no files
next to it and deploying needs no Node.

    python server/tool/embed_web.py            build with npm, then embed
    python server/tool/embed_web.py --no-build embed what is already in web/dist

Writes server/lib/web_assets.dart (commit it). A test fails if it is out of step with web/dist."""
import base64
import mimetypes
import os
import subprocess
import sys

here = os.path.dirname(os.path.abspath(__file__))
web = os.path.normpath(os.path.join(here, '..', 'web'))
dist = os.path.join(web, 'dist')
dst = os.path.normpath(os.path.join(here, '..', 'lib', 'web_assets.dart'))

if '--no-build' not in sys.argv:
    npm = 'npm.cmd' if os.name == 'nt' else 'npm'
    if not os.path.isdir(os.path.join(web, 'node_modules')):
        subprocess.run([npm, 'install'], cwd=web, check=True)
    subprocess.run([npm, 'run', 'build'], cwd=web, check=True)

types = {'.js': 'text/javascript; charset=utf-8', '.css': 'text/css; charset=utf-8', '.html': 'text/html; charset=utf-8',
         '.woff2': 'font/woff2', '.svg': 'image/svg+xml', '.png': 'image/png', '.json': 'application/json', '.ico': 'image/x-icon'}

files = []
for folder, _, names in os.walk(dist):
    for name in sorted(names):
        full = os.path.join(folder, name)
        rel = os.path.relpath(full, dist).replace(os.sep, '/')
        files.append((rel, full))
files.sort()
if not any(r == 'index.html' for r, _ in files):
    raise SystemExit('web/dist/index.html is missing: build the web client first')

out = ["// GENERATED by tool/embed_web.py from web/dist. Do not edit by hand.\n",
       "library;\n\n",
       "/// The built web client: path (relative to /app/) -> content type and base64 data.\n",
       "const Map<String, ({String type, String data})> webAssets = {\n"]
total = 0
for rel, full in files:
    data = open(full, 'rb').read()
    total += len(data)
    ext = os.path.splitext(rel)[1].lower()
    kind = types.get(ext) or mimetypes.guess_type(rel)[0] or 'application/octet-stream'
    b64 = base64.b64encode(data).decode('ascii')
    chunks = [b64[i:i + 100] for i in range(0, len(b64), 100)] or ['']
    out.append("  '%s': (\n    type: '%s',\n    data:\n" % (rel, kind))
    out.append('\n'.join("        '%s'" % c for c in chunks))
    out.append(',\n  ),\n')
out.append('};\n')
open(dst, 'w', encoding='utf-8', newline='\n').write(''.join(out))
print('embedded %d files (%d KB) in %s' % (len(files), total // 1024, os.path.relpath(dst)))
